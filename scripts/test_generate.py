"""End-to-end contracts for generated-module cleanup."""

import pathlib
import subprocess
import tempfile
import unittest


ROOT = pathlib.Path(__file__).resolve().parents[1]
GENERATOR = ROOT / ".lake/build/bin/p4spectec-gen"


class GeneratedCleanupTest(unittest.TestCase):
    def test_obsolete_modules_only(self):
        with tempfile.TemporaryDirectory() as directory:
            workspace = pathlib.Path(directory)
            export = workspace / "empty.al.json"
            export.write_text("[]\n")
            library = workspace / "FixtureSpec"

            def run(mode):
                return subprocess.run(
                    [str(GENERATOR), str(export), "--lib", "FixtureSpec",
                     "--out", str(workspace), mode],
                    capture_output=True, text=True, check=False,
                )

            initial = run("--update")
            self.assertEqual(initial.returncode, 0, initial.stderr)
            self.assertTrue((workspace / "FixtureSpec.lean").is_file())

            nested = library / "Refinement/Nested"
            nested.mkdir(parents=True)
            obsolete = nested / "Old.lean"
            obsolete.write_text(
                "-- GENERATED by p4spectec-gen for FixtureSpec; do not edit, regenerate.\n"
            )
            handwritten = nested / "Handwritten.lean"
            handwritten.write_text("namespace Handwritten\nend Handwritten\n")
            foreign = nested / "Foreign.lean"
            foreign.write_text("-- GENERATED by p4spectec-gen for AnotherSpec;\n")
            outside = workspace / "outside"
            outside.mkdir()
            linked = outside / "Linked.lean"
            linked.write_text(
                "-- GENERATED by p4spectec-gen for FixtureSpec; do not edit, regenerate.\n"
            )
            (library / "Linked").symlink_to(outside, target_is_directory=True)

            checked = run("--check")
            self.assertEqual(checked.returncode, 1)
            self.assertIn(str(obsolete), checked.stderr)
            self.assertTrue(obsolete.exists())

            updated = run("--update")
            self.assertEqual(updated.returncode, 0, updated.stderr)
            self.assertFalse(obsolete.exists())
            self.assertTrue(handwritten.exists())
            self.assertTrue(foreign.exists())
            self.assertTrue(linked.exists())
            self.assertEqual(run("--check").returncode, 0)

    def test_library_directory_symlink_is_rejected(self):
        with tempfile.TemporaryDirectory() as directory:
            workspace = pathlib.Path(directory)
            export = workspace / "empty.al.json"
            export.write_text("[]\n")
            outside = workspace / "outside"
            outside.mkdir()
            old = outside / "Old.lean"
            old.write_text(
                "-- GENERATED by p4spectec-gen for FixtureSpec; do not edit, regenerate.\n"
            )
            (workspace / "FixtureSpec").symlink_to(outside, target_is_directory=True)
            command = [str(GENERATOR), str(export), "--lib", "FixtureSpec",
                       "--out", str(workspace)]
            for mode in ("--check", "--update"):
                result = subprocess.run(
                    command + [mode], capture_output=True, text=True, check=False,
                )
                self.assertNotEqual(result.returncode, 0)
                self.assertIn("directory is a symlink", result.stderr)
                self.assertTrue(old.exists())


if __name__ == "__main__":
    unittest.main()
